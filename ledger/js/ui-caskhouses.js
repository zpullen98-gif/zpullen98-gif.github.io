/* whether the liquor shelf's bottle is the flagship itself: its name, or a
   name it is asked for by, stands whole in the flagship's name */
function caskHouseShelfIsFlagship(r, b){
  if(!r || !b) return false;
  const flag = ' ' + caskHouseFold(r.bottle && r.bottle.name) + ' ';
  return [b.name].concat(b.aka || []).some(function(n){ const f = caskHouseFold(n); return f.length >= 3 && flag.indexOf(' ' + f + ' ') >= 0; });
}

