/* The round's scope: every group, or the one group whose quiz was asked for
   (set by caskHouseAct as a round is dealt, and kept for Deal another round). */
function caskHouseQuizScope(){ const k = caskState().houseQuiz; return caskHouseGroup(k) ? k : ''; }
/* Ten questions round robin across the groups (the group order and each
   group's houses shuffled each round): one question from each house in turn,
   then each house's other question while the round is short. Each question
   carries its card's key and no bank key, so a round writes one
   progress.quizzes row and nothing reaches progress.qa, a level or a card. */
function caskHouseQuizRound(){
  const scope = caskHouseQuizScope();
  const lists = shuffle(caskHouseGroups().filter(function(g){ return !scope || g.key === scope; }).map(function(g){
    return shuffle(caskHouseHousesOf(g).filter(function(r){ return (r.quiz || []).length; })).map(function(r){ return { r: r, qs: shuffle(r.quiz.slice()) }; });
  })).filter(function(l){ return l.length; });
  const picked = [];
  for(let pass = 0; picked.length < 10 && lists.some(function(l){ return l.some(function(x){ return x.qs.length > pass; }); }); pass++){
    for(let i = 0; picked.length < 10 && lists.some(function(l){ return l.length > i; }); i++){
      lists.forEach(function(l){ const x = l[i]; if(picked.length < 10 && x && x.qs[pass]) picked.push({ r: x.r, q: x.qs[pass] }); });
    }
  }
  return picked.map(function(p){
    return { prompt: p.q.q, options: shuffle(p.q.options.slice()), answer: p.q.options[p.q.a], explain: p.q.explain, ckey: p.q.ckey, caskHouseKey: p.r.key };
  });
}
/* the Practise row's line: what a round deals with the houses here */
function caskHouseQuizLine(){
  const n = caskHouseRecords().filter(function(r){ return (r.quiz || []).length; }).length;
  const groups = caskHouseGroups().length;
  return n && groups > 1 ? 'Ten questions, one house from each group in turn. It changes no level.'
    : n ? 'Ten questions on the houses here. It changes no level.' : 'The quiz opens once the houses are here.';
}

